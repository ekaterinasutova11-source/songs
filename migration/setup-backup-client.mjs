import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const privateRoot=path.resolve('secrets/selectel-2026-10-20');
const backupRoot='D:/ffmpeg-gui/songs-project-backups/selectel';
fs.mkdirSync(backupRoot,{recursive:true});
fs.mkdirSync(path.join(backupRoot,'tools'),{recursive:true});
const downloaded=path.join(privateRoot,'tools/restic');
const binary=fs.readdirSync(downloaded).find(f=>f.endsWith('.exe'));
if(!binary)throw new Error('Verified restic executable missing');
const restic=path.join(backupRoot,'tools/restic.exe');fs.copyFileSync(path.join(downloaded,binary),restic);
const sourcePassword=path.join(privateRoot,'source-backup-password');
fs.copyFileSync(path.join(privateRoot,'deploy/backup-password'),sourcePassword);
const localPassword=path.join(privateRoot,'local-backup-password');
fs.writeFileSync(localPassword,crypto.randomBytes(48).toString('base64url')+'\n',{flag:'wx'});
const config={backupRoot,restic,sourcePassword,localPassword,sshKey:path.resolve('secrets/selectel_songs_ed25519')};
fs.writeFileSync(path.join(privateRoot,'backup-client.json'),JSON.stringify(config));
fs.copyFileSync('migration/backup-to-computer.ps1',path.join(backupRoot,'backup-to-computer.ps1'));
console.log('Independent backup client configured');
